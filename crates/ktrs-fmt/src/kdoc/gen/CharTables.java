// Regenerates ../char_tables.rs from the JDK's Character predicates (UTF-16 code units only):
//   tools/jdk/*/bin/java crates/ktrs-fmt/src/kdoc/gen/CharTables.java > crates/ktrs-fmt/src/kdoc/char_tables.rs
import java.util.function.IntPredicate;

public class CharTables {
  public static void main(String[] args) {
    System.out.println("//! Generated by `gen/CharTables.java` from JDK " + System.getProperty("java.version") + "; do not edit.");
    System.out.println("//! Sorted inclusive UTF-16 code unit ranges for `java.lang.Character` predicates.");
    emit("LETTER", c -> Character.isLetter((char) c));
    emit("DIGIT", c -> Character.isDigit((char) c));
    emit("UPPER_CASE", c -> Character.isUpperCase((char) c));
    emit("LOWER_CASE", c -> Character.isLowerCase((char) c));
    emit("JAVA_IDENTIFIER_PART", c -> Character.isJavaIdentifierPart((char) c));
  }

  static void emit(String name, IntPredicate p) {
    StringBuilder sb = new StringBuilder();
    int count = 0;
    int c = 0;
    while (c <= 0xFFFF) {
      if (!p.test(c)) {
        c++;
        continue;
      }
      int start = c;
      while (c + 1 <= 0xFFFF && p.test(c + 1)) c++;
      if (count % 8 == 0) sb.append("\n   ");
      sb.append(String.format(" (0x%04X, 0x%04X),", start, c));
      count++;
      c++;
    }
    System.out.println();
    System.out.println("pub(super) static " + name + ": [(u16, u16); " + count + "] = [" + sb + "\n];");
  }
}
